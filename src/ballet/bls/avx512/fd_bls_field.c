/* BLS12-381 tower field (Fp2/Fp12) arithmetic over the RNS base field.
   The Fp12 kernels are generated by gen_bls_fp12.py. */

#include "fd_bls_field.h"

#include "../../../third_party/blst/bindings/blst.h"
#include "fd_bls_constants.h"
#include "fd_bls_fp12_generated.inc"

typedef struct { fd_bls_fp2_t c[3]; } fp6_final_t;

void
fd_bls_fp2_mul( fd_bls_fp2_t *       out,
                fd_bls_fp2_t const * a,
                fd_bls_fp2_t const * b ) {
  /* (a0+a1*u)(b0+b1*u)=(a0b0-a1b1)+(a0b1+a1b0)u.  Each
     sum of products crosses one shared RNS reduction boundary. */
  fd_bls_fp_wide_t x, y;
  fd_bls_fp_wide_offset( &x );                         /* x      = 0 mod p.        */
  fd_bls_fp_wide_addmul( &x, &a->c[0], &b->c[0] );    /* x     += a0*b0.          */
  fd_bls_fp_wide_submul( &x, &a->c[1], &b->c[1] );    /* x     -= a1*b1.          */
  fd_bls_fp_wide_offset( &y );                         /* y      = 0 mod p.        */
  fd_bls_fp_wide_addmul( &y, &a->c[0], &b->c[1] );    /* y     += a0*b1.          */
  fd_bls_fp_wide_addmul( &y, &a->c[1], &b->c[0] );    /* y     += a1*b0.          */
  fd_bls_fp_wide_t w[2] = { x, y };
  fd_bls_fp_reduce_wide_batch2( &out->c[0], w );      /* out = (a0b0-a1b1)+(a0b1+a1b0)u. */
}

void
fd_bls_fp2_sqr( fd_bls_fp2_t *       out,
                fd_bls_fp2_t const * a ) {
  /* (a0+a1*u)^2=(a0+a1)(a0-a1)+2*a0*a1*u: two base products. */
  fd_bls_fp2_wide_t w;
  fd_bls_fp2_wide_set_sqr( &w, a );
  fd_bls_fp_reduce_wide_batch2( &out->c[0], &w.c[0] );
}

void
fd_bls_fp12_mul( fd_bls_fp12_t *       out,
                 fd_bls_fp12_t const * a,
                 fd_bls_fp12_t const * b ) {
  /* The generated kernel forms every wide product before its first
     reduction writes out, so out may alias a or b. */
  fp12_mul_generated( out, a, b );
}

void
fd_bls_fp12_sqr( fd_bls_fp12_t *       out,
                 fd_bls_fp12_t const * a ) {
  fp12_sqr_generated( out, a );
}

void
fd_bls_fp12_cyclotomic_sqr( fd_bls_fp12_t *       out,
                            fd_bls_fp12_t const * a ) {
  fp12_cyclotomic_sqr_generated( out, a );
}

void
fd_bls_fp12_mul_sparse( fd_bls_fp12_t *       out,
                        fd_bls_fp12_t const * a,
                        fd_bls_fp_t const     line[6] ) {
  fp12_mul_sparse_generated( out, a, line );
}

void
fd_bls_fp12_one( fd_bls_fp12_t * out ) {
  fd_bls_fp_one( &out->c[0] );
  for( int i=1; i<12; i++ ) fd_bls_fp_zero( &out->c[i] );
}


void
fd_bls_fp_from_normal( fd_bls_fp_t * out,
                ulong const     in[6] ) {
  fd_bls_fp_from_uint64( out, in );
}

void
fd_bls_fp2_from_normal( fd_bls_fp2_t * out,
                 ulong const      in[2][6] ) {
  fd_bls_fp_from_normal( &out->c[0], in[0] );
  fd_bls_fp_from_normal( &out->c[1], in[1] );
}

int
fd_bls_fp2_equal( fd_bls_fp2_t const * a,
           fd_bls_fp2_t const * b ) {
  return fd_bls_fp_equal( &a->c[0], &b->c[0] ) &
         fd_bls_fp_equal( &a->c[1], &b->c[1] );
}

static inline int
fd_bls_uint384_is_zero_final( ulong const a[6] ) {
  return !(a[0] | a[1] | a[2] | a[3] | a[4] | a[5]);
}

/* Public pairing inputs are not secret, so variable-time inversion is
   fine here. */
static void
fp_inverse_final( fd_bls_fp_t *       out,
                  fd_bls_fp_t const * base ) {
  ulong u[6];
  fd_bls_fp_to_uint64( u, base );
  if( FD_UNLIKELY( fd_bls_uint384_is_zero_final( u ) ) ) {
    fd_bls_fp_zero( out );
    return;
  }

  ulong r[6];
  fd_bls_fp_inv_canon( r, u );    /* variable-time safegcd on canonical limbs. */
  fd_bls_fp_from_uint64( out, r );
}

void
fd_bls_fp2_inverse( fd_bls_fp2_t *       out,
                   fd_bls_fp2_t const * in ) {
  /* (a+b*u)^-1=(a-b*u)/(a^2+b^2), since u^2=-1. */
  fd_bls_fp_t aa, bb, norm, norm_inv;
  fd_bls_fp_sqr( &aa, &in->c[0] );                       /* aa      = a^2.                 */
  fd_bls_fp_sqr( &bb, &in->c[1] );                       /* bb      = b^2.                 */
  fd_bls_fp_add( &norm, &aa, &bb );                      /* norm    = a^2+b^2.             */
  fp_inverse_final( &norm_inv, &norm );                   /* norm_inv = 1/(a^2+b^2).         */
  fd_bls_fp_mul( &out->c[0], &in->c[0], &norm_inv );     /* out.re  = a/(a^2+b^2).         */
  fd_bls_fp_mul( &out->c[1], &in->c[1], &norm_inv );     /* out.im  = b/(a^2+b^2).         */
  fd_bls_fp_neg( &out->c[1], &out->c[1] );               /* out     = (a-bu)/(a^2+b^2).    */
}


static inline void
fd_bls_fp2_mul_nonres_final( fd_bls_fp2_t *       out,
                      fd_bls_fp2_t const * in ) {
  fd_bls_fp_t a = in->c[0], b = in->c[1];
  fd_bls_fp_sub( &out->c[0], &a, &b ); /* Re((1+u)(a+bu)) = a-b, since u^2=-1. */
  fd_bls_fp_add( &out->c[1], &a, &b ); /* Im((1+u)(a+bu)) = a+b.                 */
}

static void
fd_bls_fp6_mul_final( fp6_final_t *       out,
               fp6_final_t const * a,
               fp6_final_t const * b ) {
  /* In Fp2[v]/(v^3-xi), xi=1+u.  First form every a_i*b_j, then fold
     v^3=xi and v^4=xi*v into the three output coefficients. */
  fd_bls_fp2_t a0b0, a0b1, a0b2, a1b0, a1b1, a1b2;
  fd_bls_fp2_t a2b0, a2b1, a2b2, t0, t1;
  fd_bls_fp2_mul( &a0b0, &a->c[0], &b->c[0] );       /* a0b0 = a0*b0.                                  */
  fd_bls_fp2_mul( &a0b1, &a->c[0], &b->c[1] );       /* a0b1 = a0*b1.                                  */
  fd_bls_fp2_mul( &a0b2, &a->c[0], &b->c[2] );       /* a0b2 = a0*b2.                                  */
  fd_bls_fp2_mul( &a1b0, &a->c[1], &b->c[0] );       /* a1b0 = a1*b0.                                  */
  fd_bls_fp2_mul( &a1b1, &a->c[1], &b->c[1] );       /* a1b1 = a1*b1.                                  */
  fd_bls_fp2_mul( &a1b2, &a->c[1], &b->c[2] );       /* a1b2 = a1*b2.                                  */
  fd_bls_fp2_mul( &a2b0, &a->c[2], &b->c[0] );       /* a2b0 = a2*b0.                                  */
  fd_bls_fp2_mul( &a2b1, &a->c[2], &b->c[1] );       /* a2b1 = a2*b1.                                  */
  fd_bls_fp2_mul( &a2b2, &a->c[2], &b->c[2] );       /* a2b2 = a2*b2.                                  */
  fd_bls_fp2_add( &t0, &a1b2, &a2b1 );              /* t0   = a1*b2+a2*b1, coefficient of v^3.        */
  fd_bls_fp2_mul_nonres_final( &t1, &t0 );                  /* t1   = xi*(a1*b2+a2*b1), because v^3=xi.       */
  fd_bls_fp2_add( &out->c[0], &a0b0, &t1 );         /* c0   = a0*b0+xi*(a1*b2+a2*b1).                 */
  fd_bls_fp2_add( &t0, &a0b1, &a1b0 );              /* t0   = a0*b1+a1*b0, coefficient of v.          */
  fd_bls_fp2_mul_nonres_final( &t1, &a2b2 );                /* t1   = xi*a2*b2, from a2*b2*v^4=xi*a2*b2*v.    */
  fd_bls_fp2_add( &out->c[1], &t0, &t1 );           /* c1   = a0*b1+a1*b0+xi*a2*b2.                   */
  fd_bls_fp2_add( &t0, &a0b2, &a1b1 );              /* t0   = a0*b2+a1*b1, coefficient of v^2.        */
  fd_bls_fp2_add( &out->c[2], &t0, &a2b0 );         /* c2   = a0*b2+a1*b1+a2*b0.                      */
}

static inline void
fd_bls_fp6_mul_v_final( fp6_final_t *       out,
                 fp6_final_t const * in ) {
  fp6_final_t r;
  fd_bls_fp2_mul_nonres_final( &r.c[0], &in->c[2] ); /* v*(c0+c1*v+c2*v^2) has c0'=xi*c2. */
  r.c[1] = in->c[0];                         /* c1'=c0.                              */
  r.c[2] = in->c[1];                         /* c2'=c1.                              */
  *out = r;                                  /* out=v*in modulo v^3-xi.              */
}

static void
fd_bls_fp6_inverse_final( fp6_final_t *       out,
                   fp6_final_t const * in ) {
  /* Adjugate inversion in Fp2[v]/(v^3-(1+u)); only its Fp2 norm is inverted. */
  fd_bls_fp2_t c0, c1, c2, t0, t1, tmp, tmp_inv;
  fd_bls_fp2_sqr( &c0, &in->c[0] );                   /* c0  = a0^2.                         */
  fd_bls_fp2_mul( &t0, &in->c[1], &in->c[2] );       /* t0  = a1*a2.                        */
  fd_bls_fp2_mul_nonres_final( &t1, &t0 );                   /* t1  = xi*a1*a2.                     */
  fd_bls_fp2_sub( &c0, &c0, &t1 );                   /* c0  = a0^2-xi*a1*a2.                */

  fd_bls_fp2_sqr( &t0, &in->c[2] );                  /* t0  = a2^2.                          */
  fd_bls_fp2_mul_nonres_final( &c1, &t0 );                  /* c1  = xi*a2^2.                       */
  fd_bls_fp2_mul( &t0, &in->c[0], &in->c[1] );       /* t0  = a0*a1.                         */
  fd_bls_fp2_sub( &c1, &c1, &t0 );                   /* c1  = xi*a2^2-a0*a1.                 */

  fd_bls_fp2_sqr( &c2, &in->c[1] );                  /* c2  = a1^2.                          */
  fd_bls_fp2_mul( &t0, &in->c[0], &in->c[2] );       /* t0  = a0*a2.                         */
  fd_bls_fp2_sub( &c2, &c2, &t0 );                   /* c2  = a1^2-a0*a2.                    */

  fd_bls_fp2_mul( &t0, &in->c[2], &c1 );             /* t0  = a2*c1.                         */
  fd_bls_fp2_mul( &t1, &in->c[1], &c2 );             /* t1  = a1*c2.                         */
  fd_bls_fp2_add( &tmp, &t0, &t1 );                  /* tmp = a2*c1+a1*c2.                   */
  fd_bls_fp2_mul_nonres_final( &tmp, &tmp );                 /* tmp = xi*(a2*c1+a1*c2).              */
  fd_bls_fp2_mul( &t0, &in->c[0], &c0 );             /* t0  = a0*c0.                         */
  fd_bls_fp2_add( &tmp, &tmp, &t0 );                 /* tmp = a0*c0+xi*(a2*c1+a1*c2)=Norm(a). */
  fd_bls_fp2_inverse( &tmp_inv, &tmp );                /* tmp_inv = 1/Norm(a).                  */
  fd_bls_fp2_mul( &out->c[0], &c0, &tmp_inv );       /* out0 = c0/Norm(a).                   */
  fd_bls_fp2_mul( &out->c[1], &c1, &tmp_inv );       /* out1 = c1/Norm(a).                   */
  fd_bls_fp2_mul( &out->c[2], &c2, &tmp_inv );       /* out2 = c2/Norm(a), hence out=a^-1.   */
}

void
fd_bls_fp12_inverse( fd_bls_fp12_t *       out,
                     fd_bls_fp12_t const * in ) {
  /* (a+b*w)^-1=(a-b*w)/(a^2-v*b^2) over Fp6. */
  fp6_final_t a, b, aa, bb, vb, denominator, denominator_inv, r0, r1;
  for( int i=0; i<3; i++ ) {
    a.c[i].c[0] = in->c[2*i];
    a.c[i].c[1] = in->c[2*i+1];
    b.c[i].c[0] = in->c[6+2*i];
    b.c[i].c[1] = in->c[7+2*i];
  }
  fd_bls_fp6_mul_final( &aa, &a, &a );                    /* aa          = a^2.              */
  fd_bls_fp6_mul_final( &bb, &b, &b );                    /* bb          = b^2.              */
  fd_bls_fp6_mul_v_final( &vb, &bb );                     /* vb          = v*b^2.            */
  for( int i=0; i<3; i++ )
    fd_bls_fp2_sub( &denominator.c[i], &aa.c[i], &vb.c[i] ); /* denominator = a^2-v*b^2. */
  fd_bls_fp6_inverse_final( &denominator_inv, &denominator ); /* denominator_inv = 1/(a^2-v*b^2). */
  fd_bls_fp6_mul_final( &r0, &a, &denominator_inv );      /* r0          = a/(a^2-v*b^2).   */
  fd_bls_fp6_mul_final( &r1, &b, &denominator_inv );      /* r1          = b/(a^2-v*b^2).   */
  for( int i=0; i<3; i++ )
    fd_bls_fp2_neg( &r1.c[i], &r1.c[i] );          /* r1          = -b/(a^2-v*b^2).  */
  for( int i=0; i<3; i++ ) {
    out->c[2*i]   = r0.c[i].c[0];
    out->c[2*i+1] = r0.c[i].c[1];
    out->c[6+2*i] = r1.c[i].c[0];
    out->c[7+2*i] = r1.c[i].c[1];
  }
}

static inline void
fd_bls_fp_mul2_final( fd_bls_fp_t *       out,
               fd_bls_fp_t const * a,
               fd_bls_fp_t const * ac,
               fd_bls_fp_t const * b,
               fd_bls_fp_t const * bc ) {
  fd_bls_fp_wide_t w;
  fd_bls_fp_wide_offset( &w );          /* w   = 0 mod p, represented by a positive lazy offset. */
  fd_bls_fp_wide_addmul( &w, a, ac );   /* w  += a*ac.                                            */
  fd_bls_fp_wide_addmul( &w, b, bc );   /* w  += b*bc.                                            */
  fd_bls_fp_reduce_wide( out, &w );     /* out = a*ac+b*bc mod p.                                 */
}

void
fd_bls_fp12_frobenius( fd_bls_fp12_t *       out,
                       fd_bls_fp12_t const * in,
                       ulong                 n ) {
  /* Apply x -> x^(p^n); conjugations and the fixed tower coefficients make
     this linear over Fp. */
  fd_bls_fp12_t r;
  if( n==1UL ) {
    fd_bls_fp_t f12=fd_bls_frob1_2, f13=fd_bls_frob1_3;
    fd_bls_fp_t f14=fd_bls_frob1_4, f15=fd_bls_frob1_5;
    fd_bls_fp_t f16=fd_bls_frob1_6, f17=fd_bls_frob1_7;
    fd_bls_fp_t f18=fd_bls_frob1_8, f19=fd_bls_frob1_9;
    fd_bls_fp_t f110=fd_bls_frob1_10;
    r.c[0] = in->c[0];                                                   /* c'_0  = c0.                 */
    fd_bls_fp_neg( &r.c[1], &in->c[1] );                                /* c'_1  = -c1.                */
    fd_bls_fp_mul( &r.c[2], &in->c[3], &f12 );                          /* c'_2  = f12*c3.             */
    fd_bls_fp_mul( &r.c[3], &in->c[2], &f12 );                          /* c'_3  = f12*c2.             */
    fd_bls_fp_mul( &r.c[4], &in->c[4], &f13 );                          /* c'_4  = f13*c4.             */
    fd_bls_fp_mul( &r.c[5], &in->c[5], &f14 );                          /* c'_5  = f14*c5.             */
    fd_bls_fp_mul2_final( &r.c[6],  &in->c[7],  &f16,  &in->c[6],  &f15  );   /* c'_6  = f16*c7+f15*c6.     */
    fd_bls_fp_mul2_final( &r.c[7],  &in->c[7],  &f16,  &in->c[6],  &f16  );   /* c'_7  = f16*c7+f16*c6.     */
    fd_bls_fp_mul2_final( &r.c[8],  &in->c[8],  &f17,  &in->c[9],  &f17  );   /* c'_8  = f17*c8+f17*c9.     */
    fd_bls_fp_mul2_final( &r.c[9],  &in->c[8],  &f17,  &in->c[9],  &f18  );   /* c'_9  = f17*c8+f18*c9.     */
    fd_bls_fp_mul2_final( &r.c[10], &in->c[11], &f110, &in->c[10], &f19  );   /* c'_10 = f110*c11+f19*c10.  */
    fd_bls_fp_mul2_final( &r.c[11], &in->c[11], &f110, &in->c[10], &f110 );   /* c'_11 = f110*c11+f110*c10. */
  } else if( n==2UL ) {
    fd_bls_fp_t f21=fd_bls_frob2_1, f22=fd_bls_frob2_2;
    fd_bls_fp_t f23=fd_bls_frob2_3, f25=fd_bls_frob2_5;
    r.c[0] = in->c[0]; r.c[1] = in->c[1];                    /* c'_{0,1}   = c_{0,1}.     */
    fd_bls_fp_mul( &r.c[2],  &in->c[2],  &f21 );             /* c'_2       = f21*c2.      */
    fd_bls_fp_mul( &r.c[3],  &in->c[3],  &f21 );             /* c'_3       = f21*c3.      */
    fd_bls_fp_mul( &r.c[4],  &in->c[4],  &f22 );             /* c'_4       = f22*c4.      */
    fd_bls_fp_mul( &r.c[5],  &in->c[5],  &f22 );             /* c'_5       = f22*c5.      */
    fd_bls_fp_mul( &r.c[6],  &in->c[6],  &f23 );             /* c'_6       = f23*c6.      */
    fd_bls_fp_mul( &r.c[7],  &in->c[7],  &f23 );             /* c'_7       = f23*c7.      */
    fd_bls_fp_neg( &r.c[8],  &in->c[8] );                   /* c'_8       = -c8.         */
    fd_bls_fp_neg( &r.c[9],  &in->c[9] );                   /* c'_9       = -c9.         */
    fd_bls_fp_mul( &r.c[10], &in->c[10], &f25 );            /* c'_10      = f25*c10.       */
    fd_bls_fp_mul( &r.c[11], &in->c[11], &f25 );            /* c'_11      = f25*c11.       */
  } else if( n==3UL ) {
    fd_bls_fp_t f32=fd_bls_frob3_2, f33=fd_bls_frob3_3;
    r.c[0] = in->c[0];                                                /* c'_0  = c0.               */
    fd_bls_fp_neg( &r.c[1], &in->c[1] );                             /* c'_1  = -c1.              */
    r.c[2] = in->c[3]; r.c[3] = in->c[2];                            /* c'_2  = c3; c'_3=c2.      */
    fd_bls_fp_neg( &r.c[4], &in->c[4] );                             /* c'_4  = -c4.              */
    r.c[5] = in->c[5];                                               /* c'_5  = c5.               */
    fd_bls_fp_mul2_final( &r.c[6],  &in->c[7],  &f33, &in->c[6],  &f32 );  /* c'_6  = f33*c7+f32*c6.   */
    fd_bls_fp_mul2_final( &r.c[7],  &in->c[7],  &f33, &in->c[6],  &f33 );  /* c'_7  = f33*c7+f33*c6.   */
    fd_bls_fp_mul2_final( &r.c[8],  &in->c[8],  &f32, &in->c[9],  &f32 );  /* c'_8  = f32*c8+f32*c9.   */
    fd_bls_fp_mul2_final( &r.c[9],  &in->c[8],  &f32, &in->c[9],  &f33 );  /* c'_9  = f32*c8+f33*c9.   */
    fd_bls_fp_mul2_final( &r.c[10], &in->c[11], &f32, &in->c[10], &f33 );  /* c'_10 = f32*c11+f33*c10. */
    fd_bls_fp_mul2_final( &r.c[11], &in->c[11], &f32, &in->c[10], &f32 );  /* c'_11 = f32*c11+f32*c10. */
  } else {
    r = *in;
  }
  *out = r;
}
