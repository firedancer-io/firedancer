"""fd_dasm.py preprocesses a .dasc file (C with embedded assembly) into C.

Lines starting with `|` are assembly.  Each run of assembly lines is
assembled into a constant "action list", and replaced with a call to
fd_dasm_put that replays it at run time with the values of the C
expressions used as operands.  All other lines are copied as is.  The
generated code expects DASM to evaluate to the fd_dasm_t *.

    python3 fd_dasm.py -o fd_transpile_x86.c fd_transpile_x86.dasc

See README.md for the supported syntax."""

import argparse
import os
import re
import sys
from dataclasses import dataclass
from typing import Callable, Dict, List, Optional, Union

from fd_dasm_common import DASM_VERSION, Backend, DasmError, split_statement

ERROR_MAX = 20

_RE_ASM_LINE = re.compile(r"(\s*)\|(.*)")
_RE_NAME = re.compile(r"[A-Za-z_]\w*", re.ASCII)
_RE_WORD = re.compile(r"\w+", re.ASCII)


def load_backend(arch: str, emit_put: Callable[[int, List[str]], None]) -> Backend:
    if arch == "x64":
        from fd_dasm_x86 import X86Backend

        return X86Backend(emit_put)
    if arch == "arm64":
        from fd_dasm_arm64 import Arm64Backend

        return Arm64Backend(emit_put)
    raise DasmError(f"unknown arch `{arch}' (supported: x64, arm64)")


@dataclass
class Macro:
    name: str
    params: List[str]
    body: List[str]
    lineno: int


# An output line, or a function producing lines once the whole input is
# assembled (the action list and label tables are emitted near the top
# of the file but only known at the end).
OutLine = Union[str, Callable[[], str]]


class Translator:
    def __init__(self, path: str):
        self.path = path
        self.fname = os.path.basename(path)
        self.out: List[OutLine] = []
        self.errors: List[str] = []
        self.backend: Optional[Backend] = None
        self.macros: Dict[str, Macro] = {}
        self.macro_def: Optional[Macro] = None  # macro being defined
        self.macro_active: List[str] = []  # macros being expanded
        self.lineno = 0
        self.indent = ""
        # Input line the next output line maps to under the last #line
        self.out_lineno = -1

    # -----------------------------------------------------------------------
    # Output

    def write(self, line: OutLine) -> None:
        self.out.append(line)
        self.out_lineno = self.out_lineno + 1 if isinstance(line, str) else -1

    def write_sync(self) -> None:
        if self.out_lineno != self.lineno:
            self.write(f'#line {self.lineno} "{self.fname}"')
            self.out_lineno = self.lineno

    def emit_put(self, ofs: int, args: List[str]) -> None:
        if args:
            arr = ", ".join(f"(int)({a})" for a in args)
            self.write(f"{self.indent}fd_dasm_put( DASM, {ofs}, (int const[]){{ {arr} }} );")
        else:
            self.write(f"{self.indent}fd_dasm_put( DASM, {ofs}, NULL );")

    def flush(self) -> None:
        if self.backend:
            self.backend.flush()

    # -----------------------------------------------------------------------
    # Input

    def translate(self, lines: List[str]) -> str:
        self.write(f'/* Generated by fd_dasm.py from "{self.fname}".  DO NOT EDIT! */')
        self.write("")
        for self.lineno, line in enumerate(lines, 1):
            try:
                self.do_line(line)
            except DasmError as e:
                self.error(str(e), line)
        self.flush()

        self.lineno = len(lines)
        if self.macro_def:
            self.lineno = self.macro_def.lineno
            self.error(f"unfinished .macro `{self.macro_def.name}'")
        if not self.backend:
            self.error("missing .arch directive")
        if self.errors:
            raise DasmError("\n".join(self.errors))
        return "".join((l if isinstance(l, str) else l()) + "\n" for l in self.out)

    def error(self, msg: str, line: Optional[str] = None) -> None:
        if len(self.errors) == ERROR_MAX:
            self.errors.append(f"{self.path}: too many errors, giving up")
        if len(self.errors) > ERROR_MAX:
            return
        text = f"{self.path}:{self.lineno}: error: {msg}"
        if line is not None:
            text += f"\n {line}"
        self.errors.append(text)

    def do_line(self, line: str) -> None:
        m = _RE_ASM_LINE.fullmatch(line)
        if not m:
            self.flush()
            self.write_sync()
            self.write(line)
            return

        self.indent, asm = m[1], m[2]
        self.write_sync()
        self.write(f"{self.indent}//|{asm}")
        stmt = asm.split("//")[0].strip()
        if not stmt:
            return

        if self.macro_def:
            if stmt == ".endmacro":
                self.macros[f"{self.macro_def.name}_{len(self.macro_def.params)}"] = self.macro_def
                self.macro_def = None
            else:
                self.macro_def.body.append(stmt)
            return
        self.do_stmt(stmt)

    def do_stmt(self, stmt: str) -> None:
        if stmt.endswith(":"):
            self.need_backend().label(stmt[:-1].strip())
            return

        op, params = split_statement(stmt)
        if op.startswith("."):
            handler = getattr(self, "op_" + op[1:], None)
            if handler:
                return handler(params)
            be = self.need_backend()
            if op == ".align":
                self.expect(op, params, 1)
                return be.align(params[0])
            if op in be.DATA_DIRECTIVES:
                return be.data(op, params)
            raise DasmError(f"unknown directive `{op}'")

        macro = self.macros.get(f"{op}_{len(params)}")
        if macro:
            return self.expand(macro, params)
        be = self.need_backend()
        if be.has_instruction(op, len(params)):
            return be.instruction(op, params)
        if any(be.has_instruction(op, n) or f"{op}_{n}" in self.macros for n in range(10)):
            raise DasmError(f"wrong number of operands for `{op}'")
        raise DasmError(f"unknown instruction `{op}'")

    def need_backend(self) -> Backend:
        if not self.backend:
            raise DasmError("first statement must be .arch")
        return self.backend

    @staticmethod
    def expect(op: str, params: List[str], lo: int, hi: Optional[int] = None) -> None:
        if not lo <= len(params) <= (hi or lo):
            raise DasmError(f"wrong number of parameters for `{op}'")

    def expand(self, macro: Macro, args: List[str]) -> None:
        if macro.name in self.macro_active:
            raise DasmError(f"recursive invocation of macro `{macro.name}'")
        subst = dict(zip(macro.params, args))
        self.macro_active.append(macro.name)
        try:
            for stmt in macro.body:
                try:
                    self.do_stmt(_RE_WORD.sub(lambda m: subst.get(m[0], m[0]), stmt))
                except DasmError as e:
                    raise DasmError(f"{e}\n in macro {macro.name} (line {macro.lineno}): {stmt}") from None
        finally:
            self.macro_active.pop()

    # -----------------------------------------------------------------------
    # Directives

    def op_arch(self, params: List[str]) -> None:
        self.expect(".arch", params, 1)
        if self.backend:
            raise DasmError("duplicate .arch statement")
        self.backend = load_backend(params[0], self.emit_put)
        self.write(f"#if FD_DASM_VERSION!={DASM_VERSION}")
        self.write('#error "fd_dasm.py and fd_dasm.h versions differ, regenerate this file"')
        self.write("#endif")

    def op_macro(self, params: List[str]) -> None:
        if not params:
            raise DasmError("missing macro name")
        name, mparams = params[0], params[1:]
        for p in params:
            if not _RE_NAME.fullmatch(p):
                raise DasmError(f"bad macro or parameter name `{p}'")
        if len(set(mparams)) != len(mparams):
            raise DasmError("duplicate macro parameter name")
        if f"{name}_{len(mparams)}" in self.macros:
            raise DasmError(f"duplicate macro `{name}' ({len(mparams)} parameters)")
        if self.need_backend().has_instruction(name, len(mparams)):
            raise DasmError(f"macro `{name}' shadows an instruction")
        self.macro_def = Macro(name, mparams, [], self.lineno)

    def op_endmacro(self, params: List[str]) -> None:
        raise DasmError(".endmacro without .macro")

    def op_type(self, params: List[str]) -> None:
        self.expect(".type", params, 2, 3)
        reg = params[2] if len(params) == 3 else None
        self.write(self.need_backend().define_type(params[0], params[1], reg))

    def op_actionlist(self, params: List[str]) -> None:
        """.actionlist NAME: defines the action list array here."""
        self.expect(".actionlist", params, 1)
        be = self.need_backend()
        self.write(lambda: be.format_actions(params[0]))

    def op_globals(self, params: List[str]) -> None:
        """.globals PREFIX: defines an enum of the global labels here.
        PREFIX_MAX is the label count."""
        self.expect(".globals", params, 1)
        be, prefix = self.need_backend(), params[0]

        def fmt() -> str:
            names = [f"  {prefix}{name}," for name in be.globals]
            return "\n".join(["enum {"] + names + [f"  {prefix}_MAX", "};"])

        self.write(fmt)

    def op_globalnames(self, params: List[str]) -> None:
        """.globalnames NAME: defines an array of global label names here."""
        self.expect(".globalnames", params, 1)
        be, name = self.need_backend(), params[0]

        def fmt() -> str:
            names = [f'  "{g}",' for g in be.globals]
            return "\n".join([f"static char const * const {name}[] = {{"] + names + ["  NULL", "};"])

        self.write(fmt)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Preprocess a .dasc file into C")
    ap.add_argument("input", help="input .dasc file")
    ap.add_argument("-o", "--outfile", help="output file (default: stdout)")
    args = ap.parse_args(argv)

    try:
        with open(args.input, encoding="utf-8") as f:
            lines = f.read().split("\n")
        if lines and lines[-1] == "":
            lines.pop()
        text = Translator(args.input).translate(lines)
    except (DasmError, OSError) as e:
        print(e, file=sys.stderr)
        return 1

    if not args.outfile:
        sys.stdout.write(text)
        return 0
    # Write to a temp file first so a failure never leaves a partial output
    tmp = args.outfile + ".tmp"
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, args.outfile)
    except OSError as e:
        print(e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
