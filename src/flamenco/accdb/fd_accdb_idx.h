/* Word: bits 0-15 = RANK_MAX - sum_l C(15-nib_l+l,l+1), byte 2+l = low
   byte of lane l, lanes fp descending.  All-empty is 0, and a word has
   a free lane iff lane 5 is 0. */

static inline void
fd_accdb_cf_decode( ulong w,
                    ulong fp[ FD_ACCDB_CF_LANES ] ) {
  ulong r = FD_ACCDB_CF_RANK_MAX - (w&0xFFFFUL);
  for( ulong l=FD_ACCDB_CF_LANES-1UL; l>3UL; l-- ) { /* greedy unrank */
#if FD_HAS_AVX
    __m256i v   = _mm256_load_si256( (__m256i const *)fd_accdb_cf_binom[ l ] );
    __m256i le  = _mm256_cmpeq_epi16( _mm256_min_epu16( v, _mm256_set1_epi16( (short)r ) ), v );
    ulong   cnt = (ulong)fd_uint_popcnt( (uint)_mm256_movemask_epi8( le ) )>>1;
#else
    ulong cnt = 0UL;
    for( ulong i=0UL; i<16UL; i++ ) cnt += (ulong)( fd_accdb_cf_binom[ l ][ i ]<=r );
#endif
    r -= fd_accdb_cf_binom[ l ][ cnt-1UL ];
    fp[ l ] = ( (16UL-cnt)<<8 ) | ( (w>>(16UL+8UL*l))&0xFFUL );
  }
  ulong t = fd_accdb_cf_dec4[ r ];
  for( ulong l=0UL; l<4UL; l++ ) fp[ l ] = ( ((t>>(4UL*l))&0xFUL)<<8 ) | ( (w>>(16UL+8UL*l))&0xFFUL );
}

/* fd_accdb_cf_encode: fp sorted descending. */

static inline ulong
fd_accdb_cf_encode( ulong const fp[ FD_ACCDB_CF_LANES ] ) {
  ulong r = 0UL, w = 0UL;
  for( ulong l=0UL; l<FD_ACCDB_CF_LANES; l++ ) {
    r += fd_accdb_cf_binom[ l ][ 15UL-(fp[ l ]>>8) ];
    w |= (fp[ l ]&0xFFUL)<<(16UL+8UL*l);
  }
  return w | (FD_ACCDB_CF_RANK_MAX-r);
}

static inline int
fd_accdb_cf_word_has( ulong w,
                      ulong fp ) {
  ulong x = (w>>16) ^ ( (fp&0xFFUL)*0x010101010101UL );
  if( FD_LIKELY( !( (x-0x010101010101UL) & ~x & 0x808080808080UL ) ) ) return 0; /* no low byte match */
  ulong f[ FD_ACCDB_CF_LANES ];
  fd_accdb_cf_decode( w, f );
  for( ulong l=0UL; l<FD_ACCDB_CF_LANES; l++ ) if( f[ l ]==fp ) return 1;
  return 0;
}

/* fd_accdb_cf_probe: 1 = maybe present, 0 = absent (no false
   negatives for keys inserted and not deleted). */

static inline int
fd_accdb_cf_probe( fd_accdb_cf_t const * f,
                   uchar const           pubkey[ 32 ] ) {
  if( FD_UNLIKELY( FD_VOLATILE_CONST( *f->disabled ) ) ) return 1;
  ulong i1, i2, fp;
  fd_accdb_cf_key( f, pubkey, &i1, &i2, &fp );
  for(;;) {
    ulong s = FD_VOLATILE_CONST( *f->seq );
    if( FD_UNLIKELY( s&1UL ) ) { FD_SPIN_PAUSE(); continue; }
    FD_COMPILER_MFENCE();
    if( fd_accdb_cf_word_has( FD_VOLATILE_CONST( f->cf[ i1 ] ), fp ) ) return 1;
    fd_racesan_hook( "accdb_cf:probe_mid" );
    if( fd_accdb_cf_word_has( FD_VOLATILE_CONST( f->cf[ i2 ] ), fp ) ) return 1;
    if( FD_UNLIKELY( FD_VOLATILE_CONST( *f->stash_cnt ) ) ) {
      for( ulong k=0UL; k<FD_ACCDB_CF_STASH_MAX; k++ ) {
        ulong e = FD_VOLATILE_CONST( f->stash[ k ] );
        if( e && (e&0xFFFFUL)==fp && ( (e>>16)==i1 || (e>>16)==i2 ) ) return 1;
      }
    }
    FD_COMPILER_MFENCE();
    if( FD_LIKELY( FD_VOLATILE_CONST( *f->seq )==s ) ) return 0;
  }
}

static inline int
fd_accdb_cf_free_lane( ulong w ) {
  return ( (w&0xFFFFUL)<=FD_ACCDB_CF_RANK_MAX-fd_accdb_cf_binom[ 5 ][ 15 ] /* nib_5==0 */ && !(w>>56) ) ? (int)(FD_ACCDB_CF_LANES-1UL) : -1;
}

/* fd_accdb_cf_set_lane: lane l of w (as decoded from w) becomes fp. */

static inline ulong
fd_accdb_cf_set_lane( ulong w,
                      ulong l,
                      ulong fp ) {
  ulong f[ FD_ACCDB_CF_LANES ];
  fd_accdb_cf_decode( w, f );
  for( ; l>0UL                  && f[ l-1UL ]<fp; l-- ) f[ l ] = f[ l-1UL ];
  for( ; l<FD_ACCDB_CF_LANES-1UL && f[ l+1UL ]>fp; l++ ) f[ l ] = f[ l+1UL ];
  f[ l ] = fp;
  return fd_accdb_cf_encode( f );
}

/* fd_accdb_cf_insert (writer only).  rng picks kick lanes. */

static inline void
fd_accdb_cf_insert( fd_accdb_cf_t * f,
                    uchar const     pubkey[ 32 ],
                    ulong *         rng ) {
  if( FD_UNLIKELY( *f->disabled ) ) return;
  ulong i1, i2, fp;
  fd_accdb_cf_key( f, pubkey, &i1, &i2, &fp );
  ulong bs[ 2 ] = { i1, i2 };
  for( ulong k=0UL; k<2UL; k++ ) {
    int l = fd_accdb_cf_free_lane( f->cf[ bs[ k ] ] );
    if( l>=0 ) { FD_VOLATILE( f->cf[ bs[ k ] ] ) = fd_accdb_cf_set_lane( f->cf[ bs[ k ] ], (ulong)l, fp ); return; }
  }

  /* Compute the kick path without mutating: path[j] is the bucket and
     lane whose occupant moves to path[j+1].  Abort a walk that revisits
     a bucket, so each word is edited once and its lane numbering at
     apply time is the one seen here. */
  ulong pb[ FD_ACCDB_CF_KICK_MAX+1UL ];
  ulong pl[ FD_ACCDB_CF_KICK_MAX+1UL ];
  ulong pf[ FD_ACCDB_CF_KICK_MAX+1UL ]; /* fingerprint placed into pb[j] */
  for( ulong attempt=0UL; attempt<4UL; attempt++ ) {
    *rng = fd_ulong_hash( *rng+0x9E3779B97F4A7C15UL );
    ulong b  = bs[ *rng&1UL ];
    ulong cf = fp;
    ulong n  = 0UL;
    int   ok = 0;
    for( ; n<FD_ACCDB_CF_KICK_MAX; n++ ) {
      int dup = 0;
      for( ulong j=0UL; j<n; j++ ) if( pb[ j ]==b ) { dup = 1; break; }
      if( dup ) break;
      *rng = fd_ulong_hash( *rng+1UL );
      ulong l      = *rng % FD_ACCDB_CF_LANES;
      ulong vf[ FD_ACCDB_CF_LANES ];
      fd_accdb_cf_decode( f->cf[ b ], vf );
      ulong victim = vf[ l ];
      pb[ n ] = b; pl[ n ] = l; pf[ n ] = cf;
      ulong nb2 = fd_accdb_cf_alt( f, b, victim );
      int   fl  = fd_accdb_cf_free_lane( f->cf[ nb2 ] );
      int   dup2 = 0;
      for( ulong j=0UL; j<=n; j++ ) if( pb[ j ]==nb2 ) { dup2 = 1; break; }
      if( fl>=0 && !dup2 ) {
        n++;
        pb[ n ] = nb2; pl[ n ] = (ulong)fl; pf[ n ] = victim;
        ok = 1;
        break;
      }
      cf = victim;
      b  = nb2;
    }
    if( !ok ) continue;
    FD_VOLATILE( *f->seq ) = *f->seq+1UL;
    FD_COMPILER_MFENCE();
    for( ulong j=n+1UL; j>0UL; j-- ) {
      ulong k = j-1UL;
      FD_VOLATILE( f->cf[ pb[ k ] ] ) = fd_accdb_cf_set_lane( f->cf[ pb[ k ] ], pl[ k ], pf[ k ] );
      fd_racesan_hook( "accdb_cf:kick_step" );
    }
    FD_COMPILER_MFENCE();
    FD_VOLATILE( *f->seq ) = *f->seq+1UL;
    return;
  }

  /* No path: stash the new key itself (single store). */
  for( ulong k=0UL; k<FD_ACCDB_CF_STASH_MAX; k++ ) {
    if( f->stash[ k ] ) continue;
    FD_VOLATILE( *f->stash_cnt ) = *f->stash_cnt+1UL;
    FD_COMPILER_MFENCE();
    FD_VOLATILE( f->stash[ k ] ) = (i1<<16) | fp;
    return;
  }
  FD_LOG_WARNING(( "accdb cuckoo filter stash full, disabling the filter" ));
  FD_VOLATILE( *f->disabled ) = 1UL;
}

/* fd_accdb_cf_delete (writer only): removes one copy of the key's
   fingerprint.  Only for keys known to be inserted. */

static inline void
fd_accdb_cf_delete( fd_accdb_cf_t * f,
                    uchar const     pubkey[ 32 ] ) {
  if( FD_UNLIKELY( *f->disabled ) ) return;
  ulong i1, i2, fp;
  fd_accdb_cf_key( f, pubkey, &i1, &i2, &fp );
  ulong bs[ 2 ] = { i1, i2 };
  for( ulong k=0UL; k<2UL; k++ ) {
    ulong w = f->cf[ bs[ k ] ];
    if( !fd_accdb_cf_word_has( w, fp ) ) continue;
    ulong d[ FD_ACCDB_CF_LANES ];
    fd_accdb_cf_decode( w, d );
    for( ulong l=0UL; l<FD_ACCDB_CF_LANES; l++ ) {
      if( d[ l ]!=fp ) continue;
      FD_VOLATILE( f->cf[ bs[ k ] ] ) = fd_accdb_cf_set_lane( w, l, 0UL );
      return;
    }
  }
  for( ulong k=0UL; k<FD_ACCDB_CF_STASH_MAX; k++ ) {
    ulong e = f->stash[ k ];
    if( !e || (e&0xFFFFUL)!=fp || ( (e>>16)!=i1 && (e>>16)!=i2 ) ) continue;
    FD_VOLATILE( f->stash[ k ] ) = 0UL;
    FD_COMPILER_MFENCE();
    FD_VOLATILE( *f->stash_cnt ) = *f->stash_cnt-1UL;
    return;
  }
}

