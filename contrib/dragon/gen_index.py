#!/usr/bin/env python3
"""Embeds index.html into fd_dragon_index.h, which the tile serves on GET /.

The page is emitted as a byte array rather than a string literal, which
ISO C99 only requires compilers to support up to 4095 characters."""
import pathlib
here = pathlib.Path(__file__).resolve().parent
html = (here/'index.html').read_text().encode()
out  = here.parent.parent/'src'/'discof'/'dragon'/'fd_dragon_index.h'
rows = []
for i in range(0, len(html), 16):
    rows.append('  ' + ' '.join('0x%02x,' % b for b in html[i:i+16]))
out.write_text(
"""#ifndef HEADER_fd_src_discof_dragon_fd_dragon_index_h
#define HEADER_fd_src_discof_dragon_fd_dragon_index_h

/* THIS FILE IS GENERATED BY contrib/dragon/gen_index.py FROM
   contrib/dragon/index.html.  DO NOT HAND EDIT.

   fd_dragon_index_html is the page the tile answers an HTTP/1.1
   "GET /" with, which subscribes over gRPC-Web on the same port. */

static char const fd_dragon_index_html[] = {
%s
  0x00
};

#endif /* HEADER_fd_src_discof_dragon_fd_dragon_index_h */
""" % '\n'.join(rows))
print('wrote %s (%d bytes of html)' % (out, len(html)))
